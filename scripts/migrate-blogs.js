'use strict';

const fs = require('fs');
const path = require('path');
const { computeReadTime, extractTocAndBody, writeBlogPages, dateOnly } = require('./blog-pages');

const ROOT = path.resolve(__dirname, '..');
const DATA_FILE = path.join(ROOT, 'content', 'admin-content.json');
const PUBLIC_JSON = path.join(ROOT, 'content', 'site-content.json');
const PUBLIC_JS = path.join(ROOT, 'content', 'site-content.js');

const CLUSTER_BY_HREF = {
  'blogs/digital-employee-experience.html': 'DEX & Digital Employee Experience',
  'blogs/digital-transformation-signs.html': 'Enterprise Software',
  'blogs/azure-digital-egypt-2030.html': 'Data, Cloud & Digital Egypt 2030',
  'blogs/enterprise-ai-production.html': 'AI & Automation',
  'blogs/augment-vs-outsource-tech-team.html': 'Technical Talent & Outsourcing',
};

const CATEGORY_BY_CLUSTER = {
  'DEX & Digital Employee Experience': ['enterprise-software', 'Enterprise Software'],
  'Enterprise Software': ['enterprise-software', 'Enterprise Software'],
  'Data, Cloud & Digital Egypt 2030': ['data-analytics', 'Data & Analytics'],
  'AI & Automation': ['ai-automation', 'AI & Automation'],
  'Technical Talent & Outsourcing': ['outsourcing', 'Outsourcing'],
};

function extractArticleParts(html) {
  const leadMatch = html.match(/<p class="blog-view-lead">([\s\S]*?)<\/p>/i);
  const articleMatch = html.match(/<article class="blog-view-article"[^>]*>([\s\S]*?)<\/article>/i);
  const publishedMatch = html.match(/property="article:published_time"\s+content="([^"]+)"/i);
  const modifiedMatch = html.match(/property="article:modified_time"\s+content="([^"]+)"/i);
  return {
    // answerBlock stays empty per migration plan
    body: articleMatch ? articleMatch[1].trim() : '',
    datePublished: publishedMatch ? publishedMatch[1].slice(0, 10) : '2026-06-15',
    dateModified: modifiedMatch ? modifiedMatch[1].slice(0, 10) : '2026-06-15',
    legacyLead: leadMatch ? leadMatch[1].replace(/<[^>]+>/g, '').trim() : '',
  };
}

function publicView(data) {
  const COLLECTIONS = ['services', 'partners', 'caseStudies', 'blogs', 'jobs', 'team'];
  const collections = {};
  for (const name of COLLECTIONS) {
    collections[name] = (data.collections[name] || [])
      .filter((item) => item.status === 'published')
      .sort((a, b) => Number(a.order || 0) - Number(b.order || 0));
  }
  return {
    meta: {
      version: data.meta.version,
      revision: data.meta.revision,
      updatedAt: data.meta.updatedAt,
    },
    pages: data.pages,
    collections,
  };
}

function main() {
  const data = JSON.parse(fs.readFileSync(DATA_FILE, 'utf8'));
  if (data.pages && data.pages.blogs) {
    data.pages.blogs.sectionTitle = 'Latest insights.';
  }

  for (const item of data.collections.blogs || []) {
    const href = String(item.href || '');
    const cluster = CLUSTER_BY_HREF[href];
    if (!cluster) continue;
    const filePath = path.join(ROOT, ...href.split('/'));
    if (!fs.existsSync(filePath)) {
      console.warn('Missing file for', href);
      continue;
    }
    const parts = extractArticleParts(fs.readFileSync(filePath, 'utf8'));
    const [category, categoryLabel] = CATEGORY_BY_CLUSTER[cluster];
    item.cluster = cluster;
    item.category = category;
    item.categoryLabel = categoryLabel;
    item.body = parts.body;
    item.answerBlock = '';
    item.faq = [];
    item.dataCallouts = [];
    item.relatedPosts = [];
    item.comparisonTable = null;
    item.datePublished = parts.datePublished;
    item.dateModified = dateOnly(new Date().toISOString());
    const { toc } = extractTocAndBody(item.body);
    item.tableOfContents = toc;
    item.readTime = computeReadTime(item);
    console.log(`Migrated ${href} → cluster=${cluster}, bodyWords≈${item.body.split(/\s+/).length}, readTime=${item.readTime}`);
  }

  data.meta.updatedAt = new Date().toISOString();
  data.meta.revision = Number(data.meta.revision || 0) + 1;
  fs.writeFileSync(DATA_FILE, `${JSON.stringify(data, null, 2)}\n`, 'utf8');

  const published = publicView(data);
  fs.writeFileSync(PUBLIC_JSON, `${JSON.stringify(published, null, 2)}\n`, 'utf8');
  fs.writeFileSync(
    PUBLIC_JS,
    `/* Generated by the Digital Hub CMS. Do not edit directly. */\nwindow.DH_CONTENT = ${JSON.stringify(published)};\n`,
    'utf8'
  );

  const written = writeBlogPages(data);
  console.log(`Wrote ${written} static blog pages`);
  console.log('Updated site-content.json and site-content.js');
}

main();

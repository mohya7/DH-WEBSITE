'use strict';

const fs = require('fs');
const path = require('path');
const sharp = require('sharp');

const ROOT = path.resolve(__dirname, '..');
const OUT_DIR = path.join(ROOT, 'assets', 'uploads');
const TARGET_H = 160;
const MAX_W = 560;

function partnerSlug(item) {
  const href = String(item.href || '');
  const fromHref = href.match(/(?:^|\/)([a-z0-9-]+)\.html$/i);
  if (fromHref) return fromHref[1].toLowerCase();
  const id = String(item.id || '');
  if (id.startsWith('partner-')) return id.slice('partner-'.length).toLowerCase();
  return String(item.name || 'partner').toLowerCase().replace(/[^a-z0-9]+/g, '-');
}

async function contentBox(file) {
  const { data, info } = await sharp(file).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  let minX = info.width;
  let minY = info.height;
  let maxX = 0;
  let maxY = 0;
  for (let y = 0; y < info.height; y += 1) {
    for (let x = 0; x < info.width; x += 1) {
      const i = (y * info.width + x) * 4;
      if (data[i + 3] > 12) {
        if (x < minX) minX = x;
        if (y < minY) minY = y;
        if (x > maxX) maxX = x;
        if (y > maxY) maxY = y;
      }
    }
  }
  if (maxX < minX || maxY < minY) {
    return { left: 0, top: 0, width: info.width, height: info.height };
  }
  const pad = 8;
  const left = Math.max(0, minX - pad);
  const top = Math.max(0, minY - pad);
  const width = Math.min(info.width - left, maxX - minX + 1 + pad * 2);
  const height = Math.min(info.height - top, maxY - minY + 1 + pad * 2);
  return { left, top, width, height };
}

async function normalizeLogo(srcRel, slug) {
  const src = path.join(ROOT, srcRel);
  if (!fs.existsSync(src)) throw new Error('Missing logo: ' + srcRel);
  const box = await contentBox(src);
  const trimmed = await sharp(src).extract(box).ensureAlpha().png().toBuffer();
  const meta = await sharp(trimmed).metadata();
  const scale = Math.min(TARGET_H / meta.height, MAX_W / meta.width, 1);
  const width = Math.max(1, Math.round(meta.width * scale));
  const height = Math.max(1, Math.round(meta.height * scale));
  const outRel = `assets/uploads/partner-${slug}-logo.webp`;
  const outAbs = path.join(ROOT, outRel);
  await sharp({
    create: {
      width,
      height,
      channels: 4,
      background: { r: 0, g: 0, b: 0, alpha: 0 },
    },
  })
    .composite([{ input: await sharp(trimmed).resize(width, height, { fit: 'inside' }).png().toBuffer(), gravity: 'centre' }])
    .webp({ quality: 88, alphaQuality: 95 })
    .toFile(outAbs);
  const finalMeta = await sharp(outAbs).metadata();
  return { outRel, size: `${finalMeta.width}x${finalMeta.height}` };
}

async function main() {
  const adminPath = path.join(ROOT, 'content', 'admin-content.json');
  const sitePath = path.join(ROOT, 'content', 'site-content.json');
  const admin = JSON.parse(fs.readFileSync(adminPath, 'utf8'));
  const partners = admin.collections.partners || [];
  const results = [];

  for (const item of partners) {
    if (!item.image) continue;
    const slug = partnerSlug(item);
    const result = await normalizeLogo(item.image, slug);
    item.image = result.outRel;
    results.push({ name: item.name, ...result });
  }

  fs.writeFileSync(adminPath, `${JSON.stringify(admin, null, 2)}\n`, 'utf8');

  const site = JSON.parse(fs.readFileSync(sitePath, 'utf8'));
  const byId = new Map(partners.map((p) => [p.id, p]));
  for (const item of site.collections.partners || []) {
    const src = byId.get(item.id);
    if (src) item.image = src.image;
  }
  fs.writeFileSync(sitePath, `${JSON.stringify(site, null, 2)}\n`, 'utf8');
  fs.writeFileSync(
    path.join(ROOT, 'content', 'site-content.js'),
    `/* Generated by the Digital Hub CMS. Do not edit directly. */\nwindow.DH_CONTENT = ${JSON.stringify(site)};\n`,
    'utf8'
  );

  const partnerLogos = require('./partner-logos');
  const sync = partnerLogos.syncPartnerLogos(admin);
  console.log(JSON.stringify({ results, sync }, null, 2));
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
